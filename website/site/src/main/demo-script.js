const SLOGAN = { zh: ['字在输入', '输入自在'], ja: ['字在で入力', '入力が自在'] };

const KANA = /[぀-ヿ]/;

function candLang(t, def) {
  const m = t.match(/\|(zh|ja)$/);
  if (m) return [t.slice(0, -3), m[1]];
  return [t, KANA.test(t) ? 'ja' : def];
}

function collectChars() {
  let s = '中日字在输入法演示' + SLOGAN.zh.join('') + SLOGAN.ja.join('');
  for (const se of SCRIPT)
    for (const ch of se.chunks) {
      s += ch.out;
      if (ch.c) for (const k in ch.c) for (const t of ch.c[k]) if (t[0] !== '@') s += candLang(t, 'zh')[0];
    }
  return [...new Set(s)].join('');
}
